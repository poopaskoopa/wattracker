@pytest.fixture(scope="module")
def removal_vectors() -> dict:
    return _load("removal_decision_v1.json")


def test_removal_tolerance_matches_ios_and_sits_inside_the_server_window(
    removal_vectors,
):
    from wattracker.cloud.api import _MAX_TIMESTAMP

    tolerance = removal_vectors["clock_skew_tolerance_seconds"]
    swift = CLOUD_SESSION_SWIFT.read_text(encoding="utf-8")
    match = re.search(
        r"static let clockSkewTolerance: TimeInterval = (\d+)", swift
    )
    assert match, "CloudSession.clockSkewTolerance not found"
    assert int(match.group(1)) == tolerance
    # The server has no removal rule of its own; the constant it does own is
    # the signed-request timestamp window. The client tolerance is chosen
    # strictly inside it, so a skew the server would refuse a request for is
    # never mistaken for "the server forgot this credential".
    assert removal_vectors["server_timestamp_window_seconds"] == _MAX_TIMESTAMP
    assert 0 < tolerance < _MAX_TIMESTAMP


def test_removal_vectors_cover_the_boundaries(removal_vectors):
    tolerance = removal_vectors["clock_skew_tolerance_seconds"]
    by_offset = {
        (c["status"], c["date_offset_seconds"]): c["complete_locally"]
        for c in removal_vectors["cases"]
    }
    for status in (401, 404):
        assert by_offset[(status, 0)] is True
    assert by_offset[(404, tolerance)] is True
    assert by_offset[(404, -tolerance)] is True
    assert by_offset[(404, tolerance + 1)] is False
    assert by_offset[(404, -(tolerance + 1))] is False
    for status in (429, 503, 500, 502):
        assert by_offset[(status, 0)] is False
    assert by_offset[(None, None)] is False


def test_removal_header_offsets_are_what_the_headers_say(removal_vectors):
    from datetime import datetime, timedelta, timezone

    now = datetime.fromtimestamp(removal_vectors["now_epoch"], tz=timezone.utc)
    for case in removal_vectors["cases"]:
        parsed = gen.parse_imf_fixdate(case["date_header_raw"])
        if case["date_offset_seconds"] is None:
            assert parsed is None, case["name"]
        else:
            assert parsed == now + timedelta(seconds=case["date_offset_seconds"])
