def test_calendar_vectors_match_the_desktop_grid_builder(client, calendar_vectors):
    # _calendar_data is a closure inside create_app that reads the database,
    # so it is exercised through /api/calendar against the isolated test DB
    # rather than called directly.
    for month in calendar_vectors["months"]:
        response = client.get(
            f"/api/calendar?year={month['year']}&month={month['month']}"
        )
        assert response.status_code == 200
        desktop = [
            {"iso_date": cell["date"], "day": cell["day"], "in_month": cell["in_month"]}
            for week in response.json()["weeks"]
            for cell in week
        ]
        assert desktop == month["cells"], (month["year"], month["month"])
        assert len(response.json()["weeks"]) == month["rows"]


