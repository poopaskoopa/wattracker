@pytest.fixture(scope="module")
def calendar_vectors() -> dict:
    return _load("calendar_grid_v1.json")


def test_calendar_vectors_cover_the_named_months(calendar_vectors):
    months = {(m["year"], m["month"]): m for m in calendar_vectors["months"]}

    september = months[(2026, 9)]["cells"]
    assert len(september) == 35
    assert september[0]["iso_date"] == "2026-08-31"
    assert september[-1]["iso_date"] == "2026-10-04"

    october = months[(2026, 10)]["cells"]
    assert october[0]["iso_date"] == "2026-09-28"
    assert october[3] == {"iso_date": "2026-10-01", "day": 1, "in_month": True}
    assert october[-1]["iso_date"] == "2026-11-01"

    assert months[(2026, 6)]["cells"][0] == {
        "iso_date": "2026-06-01", "day": 1, "in_month": True,
    }
    assert months[(2026, 5)]["cells"][-1] == {
        "iso_date": "2026-05-31", "day": 31, "in_month": True,
    }
    assert months[(2027, 2)]["rows"] == 4
    assert sum(c["in_month"] for c in months[(2028, 2)]["cells"]) == 29
    assert any(m["rows"] == 6 for m in calendar_vectors["months"])
    assert months[(2026, 12)]["cells"][-1]["iso_date"].startswith("2027-01-")
    assert months[(2027, 1)]["cells"][0]["iso_date"].startswith("2026-12-")


