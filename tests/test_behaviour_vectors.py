"""The Python half of the shared behaviour vectors.

``tests/vectors/calendar_grid_v1.json``, ``pairing_code_v1.json`` and
``removal_decision_v1.json`` are generated by
``scripts/generate_behaviour_vectors.py`` and read by this module, by the Swift
``BehaviourVectorTests`` and (pairing code) by the Kotlin
``PairingCodeVectorTest``.  This module proves two things for each file: that
it is exactly what the generator produces today (so nobody hand-edits a vector
to make a client pass), and that it agrees with the real implementation it
claims as its source of truth (so the generator cannot drift from the app).
"""
from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path

import pytest

from wattracker.cloud.security import (
    _MAX_PAIRING_INPUT,
    _PAIRING_ALPHABET,
    _PAIRING_FOLD,
    _PAIRING_GROUP,
    _PAIRING_STRIP,
    _PAIRING_SYMBOLS,
    format_pairing_code,
    normalize_pairing_code,
)

ROOT = Path(__file__).resolve().parents[1]
VECTORS = ROOT / "tests" / "vectors"
CLOUD_SESSION_SWIFT = (
    ROOT / "ios" / "WatTracker" / "WatTracker" / "Cloud" / "CloudSession.swift"
)

_SPEC = importlib.util.spec_from_file_location(
    "generate_behaviour_vectors", ROOT / "scripts" / "generate_behaviour_vectors.py"
)
gen = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(gen)


def _load(name: str) -> dict:
    return json.loads((VECTORS / name).read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# Drift: the committed files are exactly the generator's output.
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("path", sorted(gen.OUTPUTS), ids=lambda p: p.name)
def test_vector_file_is_exactly_what_the_generator_writes(path):
    build, ensure_ascii = gen.OUTPUTS[path]
    assert path.read_text(encoding="utf-8") == gen.render(build, ensure_ascii), (
        f"{path.name} is stale or hand-edited; run "
        "python scripts/generate_behaviour_vectors.py"
    )


@pytest.mark.parametrize("path", sorted(gen.OUTPUTS), ids=lambda p: p.name)
def test_vector_file_declares_version_description_and_source(path):
    data = json.loads(path.read_text(encoding="utf-8"))
    assert data["version"] == 1
    assert data["description"]
    assert data["source_of_truth"]
    assert data["generated_by"] == "scripts/generate_behaviour_vectors.py"


