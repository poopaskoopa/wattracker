@pytest.fixture(scope="module")
def pairing_vectors() -> dict:
    return _load("pairing_code_v1.json")


def test_pairing_vectors_declare_the_server_constants(pairing_vectors):
    assert pairing_vectors["alphabet"] == _PAIRING_ALPHABET
    assert pairing_vectors["folds"] == dict(_PAIRING_FOLD)
    assert set(pairing_vectors["server_strip"]) == set(_PAIRING_STRIP)
    assert pairing_vectors["symbol_count"] == _PAIRING_SYMBOLS
    assert pairing_vectors["group_size"] == _PAIRING_GROUP
    assert pairing_vectors["max_input_length"] == _MAX_PAIRING_INPUT
    # The client leniency must never overlap what the server already strips,
    # or "client_may_accept" would be describing server behaviour.
    assert not set(pairing_vectors["client_extra_strip"]) & set(_PAIRING_STRIP)


def test_every_pairing_vector_matches_the_server(pairing_vectors):
    for case in pairing_vectors["cases"]:
        value = case["input"]
        assert normalize_pairing_code(value) == case["normalized"], case["name"]
        if case["normalized"] is None:
            assert case["grouped"] is None, case["name"]
            with pytest.raises(ValueError):
                format_pairing_code(value)
        else:
            assert format_pairing_code(value) == case["grouped"], case["name"]


def test_client_leniency_is_only_ever_stripped_line_breaks(pairing_vectors):
    extra = pairing_vectors["client_extra_strip"]
    lenient = [c for c in pairing_vectors["cases"] if c.get("client_may_accept")]
    assert {c["name"] for c in lenient} == {
        "trailing-newline", "trailing-crlf", "embedded-newlines", "embedded-cr",
    }
    for case in lenient:
        assert case["normalized"] is None, case["name"]
        stripped = "".join(c for c in case["input"] if c not in extra)
        assert normalize_pairing_code(stripped) == case["client_normalized"]
        assert format_pairing_code(stripped) == case["client_grouped"]


